#[test]
fn linux_packages_carry_the_helper_and_its_uinput_rule() {
    let rule = include_str!("../linux/60-whispernow-uinput.rules");
    let script = include_str!("../../../scripts/install_input_helper.sh");
    assert!(
        script.contains(rule),
        "the install script writes the packaged rule"
    );
    let config: serde_json::Value =
        serde_json::from_str(include_str!("../tauri.linux.conf.json")).expect("valid JSON");
    let linux = &config["bundle"]["linux"];
    let helper = "/usr/libexec/whispernow/whispernow-input-helper";
    for package in ["deb", "rpm"] {
        let package = &linux[package];
        assert!(package["files"][helper].is_string());
        assert_eq!(
            package["files"]["/usr/lib/udev/rules.d/60-whispernow-uinput.rules"],
            "linux/60-whispernow-uinput.rules"
        );
        assert_eq!(package["postInstallScript"], "linux/postinst.sh");
    }
    assert!(include_str!("../linux/postinst.sh").contains(helper));
    let appimage = &linux["appimage"]["files"];
    assert!(appimage[helper].is_string());
    assert!(appimage["/usr/share/whispernow/install_input_helper.sh"].is_string());
}
