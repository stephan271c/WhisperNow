#[test]
fn production_csp_allows_the_dioxus_webassembly_frontend() {
    let config: serde_json::Value =
        serde_json::from_str(include_str!("../tauri.conf.json")).expect("valid JSON");
    let csp = config["app"]["security"]["csp"]
        .as_str()
        .expect("desktop CSP");

    assert!(csp.contains("script-src 'self' 'wasm-unsafe-eval'"));
    assert!(!csp.contains("'unsafe-eval'"));
    // History playback plays WAV bytes from an in-memory blob; no media origin
    // beyond the app itself is allowed.
    assert!(csp.contains("media-src 'self' blob:;"));
}

