/// A snapshot in `phase` with the default model ready.
pub(crate) fn snapshot(phase: PhaseDto) -> AppStateDto {
    AppStateDto {
        phase,
        selected_model_id: whispernow_domain::ModelId::default(),
        model_state: ModelStateDto::Ready,
        last_transcript: None,
        error: None,
        active_downloads: Vec::new(),
        setup_test: None,
    }
}

pub(crate) const fn recording() -> PhaseDto {
    PhaseDto::Recording {
        mode: RecordingMode::Toggle,
        session: 1,
    }
}

/// The app commands each window's capabilities allow, by window label.
fn allowed_commands_by_window(manifest_dir: &Path) -> BTreeMap<String, BTreeSet<String>> {
    let mut allowed_by_window: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for entry in std::fs::read_dir(manifest_dir.join("capabilities")).expect("capabilities") {
        let path = entry.expect("capability entry").path();
        let capability: serde_json::Value =
            serde_json::from_str(&std::fs::read_to_string(&path).expect("capability file"))
                .expect("capability JSON");
        let app_permissions: Vec<String> = capability["permissions"]
            .as_array()
            .expect("capability permissions")
            .iter()
            .map(|permission| permission.as_str().expect("permission identifier"))
            .filter(|permission| !permission.starts_with("core:"))
            .map(|permission| {
                permission
                    .strip_prefix("allow-")
                    .unwrap_or_else(|| panic!("{path:?} grants non-allow permission {permission}"))
                    .replace('-', "_")
            })
            .collect();
        for window in capability["windows"]
            .as_array()
            .expect("capability windows")
        {
            allowed_by_window
                .entry(window.as_str().expect("window label").to_owned())
                .or_default()
                .extend(app_permissions.iter().cloned());
        }
    }
    allowed_by_window
}

/// Every place that names a desktop command must name the same set: the api
/// catalog, the list build.rs handed to Tauri, the registered invoke handler,
/// the committed permission files, and the per-window capabilities.
#[test]
fn command_catalog_is_identical_across_build_handler_permissions_and_capabilities() {
    let catalog: BTreeSet<&str> = COMMAND_NAMES.into_iter().collect();
    assert_eq!(
        catalog.len(),
        COMMAND_NAMES.len(),
        "COMMAND_NAMES repeats a name"
    );

    let build_commands: BTreeSet<&str> = env!("WHISPERNOW_TAURI_MANIFEST_COMMANDS")
        .split(',')
        .collect();
    assert_eq!(build_commands, catalog, "build.rs Tauri manifest commands");

    let registered: Vec<&str> = REGISTERED_COMMANDS
        .iter()
        .map(|path| {
            path.rsplit_once("::")
                .map_or(*path, |(_, name)| name)
                .trim()
        })
        .collect();
    assert_eq!(
        registered.len(),
        catalog.len(),
        "a handler is registered twice"
    );
    assert_eq!(
        registered.into_iter().collect::<BTreeSet<_>>(),
        catalog,
        "generate_handler! commands"
    );

    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let permission_files: BTreeSet<String> =
        std::fs::read_dir(manifest_dir.join("permissions/autogenerated"))
            .expect("autogenerated permissions directory")
            .map(|entry| {
                entry
                    .expect("permission file entry")
                    .file_name()
                    .into_string()
                    .expect("UTF-8 permission file name")
            })
            .collect();
    let expected_files: BTreeSet<String> = catalog
        .iter()
        .map(|command| format!("{command}.toml"))
        .collect();
    assert_eq!(
        permission_files, expected_files,
        "permissions/autogenerated"
    );

    let allowed_by_window = allowed_commands_by_window(manifest_dir);
    let all_commands: BTreeSet<String> = catalog.iter().map(ToString::to_string).collect();
    // The overlay reads state, and its controls stop, cancel, dismiss, copy the unpasted
    // transcript, or open the main window; nothing else.
    let recording_bar_commands = [
        "get_state",
        "stop_recording",
        "cancel_recording",
        "dismiss_recording_overlay",
        "copy_last_transcript",
        "open_main_window",
    ]
    .map(str::to_owned);
    let recording_bar_commands = BTreeSet::from(recording_bar_commands);
    assert_eq!(
        allowed_by_window,
        BTreeMap::from([
            (SETTINGS_WINDOW.to_owned(), all_commands),
            (RECORDING_BAR_WINDOW.to_owned(), recording_bar_commands),
        ]),
        "capability allow-* entries per window"
    );
}

#[test]
fn recording_bar_never_steals_focus() {
    let config: serde_json::Value =
        serde_json::from_str(include_str!("../tauri.conf.json")).expect("valid JSON");
    let bar_window = config["app"]["windows"]
        .as_array()
        .expect("configured windows")
        .iter()
        .find(|window| window["label"] == RECORDING_BAR_WINDOW)
        .expect("recording bar window");
    assert_eq!(bar_window["focusable"], false);
    assert_eq!(bar_window["focus"], false);
    assert_eq!(bar_window["alwaysOnTop"], true);
    // Buttons respond to the first click without activating the app first (macOS).
    assert_eq!(bar_window["acceptFirstMouse"], true);
    assert_eq!(
        (bar_window["width"].as_f64(), bar_window["height"].as_f64()),
        (
            Some(crate::overlay::OVERLAY_LOGICAL_SIZE.0),
            Some(crate::overlay::OVERLAY_LOGICAL_SIZE.1)
        )
    );
}

